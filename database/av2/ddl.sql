BEGIN;

-- Evita aplicar acidentalmente a entrega academica sobre tabelas da aplicacao.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    ) THEN
        RAISE EXCEPTION 'Banco nao esta vazio: PI4-242 requer banco de desenvolvimento vazio. Nenhuma tabela sera alterada.';
    END IF;
END $$;

-- 1. Usuarios e especializacoes (PK dos subtipos tambem FK para usuarios)
CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL, -- somente hash; jamais texto puro
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_nome CHECK (BTRIM(nome) <> ''),
    CONSTRAINT ck_usuarios_email CHECK (BTRIM(email) <> ''),
    CONSTRAINT ck_usuarios_senha CHECK (BTRIM(senha) <> '')
);

CREATE TABLE compradores (
    id_usuario INTEGER NOT NULL,
    cpf VARCHAR(11),
    data_nascimento DATE,
    CONSTRAINT pk_compradores PRIMARY KEY (id_usuario),
    CONSTRAINT fk_compradores_usuarios FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT uq_compradores_cpf UNIQUE (cpf),
    CONSTRAINT ck_compradores_cpf CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$')
);

CREATE TABLE artesaos (
    id_usuario INTEGER NOT NULL,
    nome_artesao VARCHAR(150) NOT NULL,
    regiao_producao VARCHAR(120) NOT NULL,
    CONSTRAINT pk_artesaos PRIMARY KEY (id_usuario),
    CONSTRAINT fk_artesaos_usuarios FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT ck_artesaos_nome CHECK (BTRIM(nome_artesao) <> ''),
    CONSTRAINT ck_artesaos_regiao CHECK (BTRIM(regiao_producao) <> '')
);

CREATE TABLE administradores (
    id_usuario INTEGER NOT NULL,
    nivel_acesso VARCHAR(50) NOT NULL,
    CONSTRAINT pk_administradores PRIMARY KEY (id_usuario),
    CONSTRAINT fk_administradores_usuarios FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT ck_administradores_nivel CHECK (BTRIM(nivel_acesso) <> '')
);

-- 2. Enderecos: vinculados aos pedidos, nao obrigatoriamente ao comprador.
CREATE TABLE enderecos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    logradouro VARCHAR(180) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    cep VARCHAR(8) NOT NULL,
    complemento VARCHAR(180),
    CONSTRAINT pk_enderecos PRIMARY KEY (id),
    CONSTRAINT ck_enderecos_logradouro CHECK (BTRIM(logradouro) <> ''),
    CONSTRAINT ck_enderecos_numero CHECK (BTRIM(numero) <> ''),
    CONSTRAINT ck_enderecos_bairro CHECK (BTRIM(bairro) <> ''),
    CONSTRAINT ck_enderecos_cidade CHECK (BTRIM(cidade) <> ''),
    CONSTRAINT ck_enderecos_uf CHECK (estado ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_enderecos_cep CHECK (cep ~ '^[0-9]{8}$')
);

-- 3. Produtos e imagens
CREATE TABLE produtos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(180) NOT NULL,
    descricao TEXT NOT NULL,
    materia_prima VARCHAR(120),
    tecnica VARCHAR(120) NOT NULL,
    regiao_producao VARCHAR(120) NOT NULL,
    categoria VARCHAR(100) NOT NULL, -- campo textual; nao ha tabela categoria no logico
    tipo VARCHAR(20) NOT NULL DEFAULT 'LOTE',
    preco NUMERIC(12,2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL DEFAULT 0,
    dimensoes VARCHAR(180),
    guia_cuidados TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'RASCUNHO',
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_artesao INTEGER NOT NULL,
    CONSTRAINT pk_produtos PRIMARY KEY (id),
    CONSTRAINT fk_produtos_artesaos FOREIGN KEY (id_artesao)
        REFERENCES artesaos (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_produtos_titulo CHECK (BTRIM(titulo) <> ''),
    CONSTRAINT ck_produtos_descricao CHECK (BTRIM(descricao) <> ''),
    CONSTRAINT ck_produtos_tecnica CHECK (BTRIM(tecnica) <> ''),
    CONSTRAINT ck_produtos_regiao CHECK (BTRIM(regiao_producao) <> ''),
    CONSTRAINT ck_produtos_categoria CHECK (BTRIM(categoria) <> ''),
    CONSTRAINT ck_produtos_tipo CHECK (tipo IN ('UNICO','LOTE')),
    CONSTRAINT ck_produtos_preco CHECK (preco > 0),
    CONSTRAINT ck_produtos_estoque CHECK (quantidade_estoque >= 0),
    CONSTRAINT ck_produtos_unico_estoque CHECK (tipo <> 'UNICO' OR quantidade_estoque <= 1),
    CONSTRAINT ck_produtos_status CHECK (status IN ('RASCUNHO','ATIVO','PAUSADO','INATIVO'))
);

CREATE TABLE imagens_produto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    url_imagem VARCHAR(2048) NOT NULL,
    id_produto INTEGER NOT NULL,
    CONSTRAINT pk_imagens_produto PRIMARY KEY (id),
    CONSTRAINT fk_imagens_produto_produtos FOREIGN KEY (id_produto)
        REFERENCES produtos (id) ON DELETE CASCADE,
    CONSTRAINT uq_imagens_produto_url UNIQUE (id_produto, url_imagem),
    CONSTRAINT ck_imagens_produto_url CHECK (BTRIM(url_imagem) <> '')
);

-- 4. Carrinhos e seus itens
CREATE TABLE carrinhos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_comprador INTEGER NOT NULL,
    CONSTRAINT pk_carrinhos PRIMARY KEY (id),
    CONSTRAINT fk_carrinhos_compradores FOREIGN KEY (id_comprador)
        REFERENCES compradores (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE itens_carrinho (
    id_carrinho INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_itens_carrinho PRIMARY KEY (id_carrinho, id_produto),
    CONSTRAINT fk_itens_carrinho_carrinhos FOREIGN KEY (id_carrinho)
        REFERENCES carrinhos (id) ON DELETE CASCADE,
    CONSTRAINT fk_itens_carrinho_produtos FOREIGN KEY (id_produto)
        REFERENCES produtos (id) ON DELETE RESTRICT,
    CONSTRAINT ck_itens_carrinho_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_itens_carrinho_preco CHECK (preco_unitario > 0)
);

-- 5. Pedidos e seus itens
CREATE TABLE pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_pedido TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDENTE',
    valor_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    id_comprador INTEGER NOT NULL,
    id_endereco INTEGER NOT NULL,
    CONSTRAINT pk_pedidos PRIMARY KEY (id),
    CONSTRAINT fk_pedidos_compradores FOREIGN KEY (id_comprador)
        REFERENCES compradores (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_pedidos_enderecos FOREIGN KEY (id_endereco)
        REFERENCES enderecos (id) ON DELETE RESTRICT,
    CONSTRAINT ck_pedidos_status CHECK (status IN (
        'PENDENTE','CONFIRMADO','EM_PREPARACAO','ENVIADO','ENTREGUE','CANCELADO'
    )),
    CONSTRAINT ck_pedidos_valor_total CHECK (valor_total >= 0)
);

CREATE TABLE itens_pedido (
    id_pedido INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_itens_pedido PRIMARY KEY (id_pedido, id_produto),
    CONSTRAINT fk_itens_pedido_pedidos FOREIGN KEY (id_pedido)
        REFERENCES pedidos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_itens_pedido_produtos FOREIGN KEY (id_produto)
        REFERENCES produtos (id) ON DELETE RESTRICT,
    CONSTRAINT ck_itens_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_itens_pedido_preco CHECK (preco_unitario > 0),
    CONSTRAINT ck_itens_pedido_subtotal CHECK (subtotal = quantidade * preco_unitario)
);

-- 6. Envios e avaliacoes
CREATE TABLE postagens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    data_postagem TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    transportadora VARCHAR(100) NOT NULL,
    codigo_rastreio VARCHAR(100),
    id_pedido INTEGER NOT NULL,
    id_artesao INTEGER NOT NULL,
    CONSTRAINT pk_postagens PRIMARY KEY (id),
    CONSTRAINT fk_postagens_pedidos FOREIGN KEY (id_pedido)
        REFERENCES pedidos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_postagens_artesaos FOREIGN KEY (id_artesao)
        REFERENCES artesaos (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_postagens_transportadora CHECK (BTRIM(transportadora) <> ''),
    CONSTRAINT ck_postagens_codigo CHECK (
        codigo_rastreio IS NULL OR BTRIM(codigo_rastreio) <> ''
    )
);

CREATE TABLE avaliacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nota INTEGER NOT NULL,
    comentario TEXT,
    data TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_comprador INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    CONSTRAINT pk_avaliacoes PRIMARY KEY (id),
    CONSTRAINT fk_avaliacoes_compradores FOREIGN KEY (id_comprador)
        REFERENCES compradores (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_avaliacoes_produtos FOREIGN KEY (id_produto)
        REFERENCES produtos (id) ON DELETE RESTRICT,
    CONSTRAINT ck_avaliacoes_nota CHECK (nota BETWEEN 1 AND 5)
);

-- Indices de apoio a relacionamentos, listagem e futura recomendacao de IA.
CREATE INDEX idx_produtos_artesao ON produtos (id_artesao);
CREATE INDEX idx_produtos_categoria_status ON produtos (categoria, status);
CREATE INDEX idx_produtos_tecnica ON produtos (tecnica);
CREATE INDEX idx_produtos_regiao ON produtos (regiao_producao);
CREATE INDEX idx_imagens_produto_produto ON imagens_produto (id_produto);
CREATE INDEX idx_carrinhos_comprador ON carrinhos (id_comprador);
CREATE INDEX idx_itens_carrinho_produto ON itens_carrinho (id_produto);
CREATE INDEX idx_pedidos_comprador_data ON pedidos (id_comprador, data_pedido);
CREATE INDEX idx_pedidos_endereco ON pedidos (id_endereco);
CREATE INDEX idx_itens_pedido_produto ON itens_pedido (id_produto);
CREATE INDEX idx_postagens_pedido_artesao ON postagens (id_pedido, id_artesao);
CREATE INDEX idx_postagens_artesao ON postagens (id_artesao);
CREATE INDEX idx_avaliacoes_comprador ON avaliacoes (id_comprador);
CREATE INDEX idx_avaliacoes_produto ON avaliacoes (id_produto);

COMMIT;
